package driverbuild

import (
	"errors"
	"fmt"
	"path/filepath"
	"strings"
)

// CheckModule says whether the fetched source is the module it was asked for. A repository that declares another module path
// would be built in under a name that nobody reviewed, and could shadow a module securl already uses.
func (f Fetched) CheckModule() error {
	got, err := ModulePath(f.Dir)
	if err != nil {
		return fmt.Errorf("driver %s: it has no go.mod with a module line, so it is not a Go module", f.Spec.Module())
	}
	if got != f.Spec.Module() {
		return fmt.Errorf("driver %s: its go.mod declares another module path than the repository it was fetched from", f.Spec.Module())
	}
	return nil
}

// plainDir says whether a directory can stand in a go.mod replace line without ending it: absolute, with nothing that a go.mod
// reads as a separator, a quote or a comment.
func plainDir(dir string) bool {
	if !filepath.IsAbs(dir) || strings.Contains(dir, "//") {
		return false
	}
	for _, r := range dir {
		if r <= ' ' || r == '"' || r == '`' || r == '\\' || r == 0x7f {
			return false
		}
	}
	return true
}

// Modfile returns base (the contents of securl's go.mod) with each fetched driver required and replaced by its directory. The
// result is written to a file of its own and given to go with -modfile, so the repository's go.mod and go.sum are never touched.
func Modfile(base string, drivers []Fetched) (string, error) {
	if len(drivers) == 0 {
		return base, nil
	}
	var b strings.Builder
	b.WriteString(strings.TrimRight(base, "\n"))
	b.WriteString("\n")
	for _, d := range drivers {
		m := d.Spec.Module()
		if _, err := ParseSpec(m + "@" + d.Spec.Rev); err != nil {
			return "", errors.New("a driver's module path is not a plain path")
		}
		if !plainDir(d.Dir) {
			return "", fmt.Errorf("driver %s: the build directory is not a plain absolute path", m)
		}
		if strings.Contains(base, m) {
			return "", fmt.Errorf("driver %s: securl's go.mod already mentions this module", m)
		}
		fmt.Fprintf(&b, "\nrequire %s v0.0.0\nreplace %s => %s\n", m, m, d.Dir)
	}
	return b.String(), nil
}

// Source returns the Go file that links the drivers in: a blank import of each, in the order given. A driver registers itself in
// an init function, so importing it is all it takes. When record is the import path of securl's mcpserver package, the file also
// stores which commit of which driver was built in, so the binary can say so (securl version) without a build script having to
// remember to pass it on. No driver, no file.
func Source(drivers []Fetched, record string) string {
	if len(drivers) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("// Code generated by generate.go; DO NOT EDIT.\n\npackage main\n\nimport (\n")
	if record != "" {
		fmt.Fprintf(&b, "\t%q\n\n", record)
	}
	for _, d := range drivers {
		fmt.Fprintf(&b, "\t_ %q\n", d.Spec.Module())
	}
	b.WriteString(")\n")
	if record != "" {
		b.WriteString("\nfunc init() {\n\tmcpserver.ExternalDrivers = []string{\n")
		for _, d := range drivers {
			fmt.Fprintf(&b, "\t\t%q,\n", d.Spec.Module()+"@"+d.Commit)
		}
		b.WriteString("\t}\n}\n")
	}
	return b.String()
}
